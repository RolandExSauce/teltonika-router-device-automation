//get current date
const currentDate = () => {
  let today: Date | string = "";
  today = new Date();
  let dd = today.getDate();
  let mm = today.getMonth() + 1;
  const y = today.getFullYear();
  if (dd < 10) {
    dd = parseInt("0") + dd;
  }
  if (mm < 10) {
    mm = parseInt("0") + mm;
  }
  today = String(mm) + "-" + String(dd) + "-" + String(y);
  return today;
};

//remove unecessary fields from array
const modData = async (routerData: any) => {
  const modRouterArr = routerData.map((router: any) => {
    //To fix any here, fields has to be optionals, but this will be hard cuz types are coming from Router interface generated by codegen
    //"any" cuz we want to delete keys, else ts wont let
    delete router.dfltRouterPass;
    delete router.isConfigured;
    delete router.modell;
    delete router.__typename;
    if (router.ipAdress) delete router.ipAdress;
    if (router.routerPassShell) delete router.routerPassShell;
    if (router.dfltWifiPass) delete router.dfltWifiPass;
    return router as Router;
  });
  return Promise.all(modRouterArr);
};


export const downloadData = async (data: Router[]) => {
  const body = (await modData(data)) as any;
  //headers for excel file, show only necessary fields
  const csvHeaders = [
    "Router SSID",
    "Serial Number",
    "WebUser PW",
    "WebCLI User",
    "WIFI PW",
  ];

  //download excel function
  const res = downloadExcel({
    fileName: `router-tabelle-${currentDate()}`,
    sheet: `Teltonika-Router-${currentDate()}`, //name of excel sheet
    tablePayload: {
      header: csvHeaders,
      body,
    },
  });

  //cuz we want to display download success message or failed
  if (res) return true;
  else return false;
};

